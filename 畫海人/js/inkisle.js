// 哪一區（0 = 墨水的河，走不過去；門也在河上）
export function inkRegion(c, r) {
  const ring = ((c === 4 || c === 11) && r >= 4 && r <= 11) || ((r === 4 || r === 11) && c >= 4 && c <= 11);
  if (ring || (c === 7 && r >= 12) || (r === 7 && c >= 12) || (c === 8 && r <= 3) || (r === 8 && c <= 3)) return 0;
  if (c >= 5 && c <= 10 && r >= 5 && r <= 10) return 5;
  if ((r >= 12 && c <= 6) || (r >= 9 && r <= 11 && c <= 3)) return 1;
  if ((r >= 12 && c >= 8) || (r >= 8 && r <= 11 && c >= 12)) return 2;
  if ((r <= 3 && c >= 9) || (r >= 4 && r <= 6 && c >= 12)) return 3;
  return 4;
}

