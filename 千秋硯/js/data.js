export function elementMult(atk, def) {
  if (!atk || atk === '無' || !def || def === '無') return 1;
  if ((atk === '陰' && def === '陽') || (atk === '陽' && def === '陰')) return 1.3;
  if (atk === def) return 0.8;
  if (OVERCOME[atk] === def) return 1.5;
  if (OVERCOME[def] === atk) return 0.7;
  return 1;
}

