// 這一卷的謎題：從同一個劇本檔裡用到的問答小遊戲，挑沒有圖形的題目
function riddlePool(ctx, file) {
  const ids = new Set();
  for (const s of Object.values(ctx.scenes)) {
    if (s.file !== file) continue;
    for (const c of s.cmds) if (c.t === 'cmd' && c.name === '小遊戲') { const [k, id] = c.arg.split(/\s+/); if (['識字', '譯字', '牽星', '透視'].includes(k)) ids.add(id); }
  }
  const out = [];
  for (const id of ids) (TRANSLATE[id]?.items || []).forEach((it, i) => { if (!it.glyph && it.opts && it.a) out.push({ id, i, it }); });
  return out;
}

const pick = a => a[Math.floor(Math.random() * a.length)];
const shuffle = a => a.map(x => [Math.random(), x]).sort((p, q) => p[0] - q[0]).map(p => p[1]);

// 打開小地圖。回傳要跳去的場景（'→場景'）或 'stop'
export async function walkMap(ctx, runner, pool, out) {
  const g = ctx.g, ui = ctx.ui;
  const vol = runner.volId();
  const here = ctx.scenes[g.scene];
  const tier = Math.max(0, VOLUMES.findIndex(v => v.id === vol)) + 1;
  const spots = [];
  const pos = shuffle(SPOTS);
  spots.push({ k: '妖', p: pos.pop() }, { k: '妖', p: pos.pop() });
  const tr = out && out.寶 && ctx.scenes[out.寶];
  if (tr) {
    const c0 = tr.cmds[0];
    spots.push({ k: '寶', p: pos.pop(), done: c0 && c0.t === 'if' && checkCond(g, c0.cond) });
  }
  const evs = (WALK_EVENTS[vol] || []).map((e, i) => ({ e, i })).filter(({ i }) => !g.flags[`路人.${vol}.${i}`]);
  if (evs.length) spots.push({ k: '人', p: pos.pop(), ev: pick(evs) });
  const rs = here ? riddlePool(ctx, here.file) : [];
  if (rs.length) spots.push({ k: '謎', p: pos.pop(), q: pick(rs) });
  spots.push({ k: '歇', p: pos.pop() });

  const box = el('div', { class: 'overlay open walkmap' });
  document.body.appendChild(box);
  const exit = r => { box.remove(); return r; };
  for (;;) {
    const r = await showMap(ctx, spots, box);
    if (r === 'leave') return exit(out && out.回 ? '→' + out.回 : undefined);
    const s = spots[r];
    if (s.k === '妖') {
      const res = await ctx.battle.start('隨機', pool, false);
      if (res === 'quit') return exit('stop');
      ctx.showStory(); ctx.audio.music(g.loc.music);
      if (res === 'win') s.done = true;
    } else if (s.k === '寶') {
      return exit('→' + out.寶);
    } else if (s.k === '人') {
      await passerby(ctx, runner, vol, s.ev);
      s.done = true;
    } else if (s.k === '謎') {
      await riddle(ctx, runner, s.q, tier);
      s.done = true;
    } else if (s.k === '歇') {
      for (const n of g.party) { const m = g.members[n]; const st = memberStats(g, m); m.hp = Math.min(st.hp, m.hp + Math.round(st.hp * 0.35)); m.mp = Math.min(st.mp, m.mp + Math.round(st.mp * 0.35)); }
      ctx.audio.sfx('heal');
      ui.toast('你們坐下來，喘了一口氣。全隊的體與墨回復了一些。');
      s.done = true;
    }
  }
}

function showMap(ctx, spots, box) {
  const g = ctx.g, ui = ctx.ui;
  return new Promise(resolve => {
    box.innerHTML = '';
    const bg = g.loc && g.loc.bg;
    const field = el('div', { class: 'wm-field' });
    if (ui.hasImg('bg', bg)) field.style.backgroundImage = `url("${ui.imgSrc('bg', bg, 800)}")`;
    const tip = el('p', { class: 'wm-tip' }, '點地圖上的記號。妖物可以繞過去；寶物和路人，可能只會遇到一次。');
    spots.forEach((s, i) => {
      const k = KIND[s.k];
      field.appendChild(el('button', { class: `wm-spot k-${s.k}` + (s.done ? ' done' : ''), style: { left: s.p[0] + '%', top: s.p[1] + '%' }, disabled: !!s.done, 'aria-label': k.name,
        onclick: () => { ctx.audio.sfx('tap'); close(i); } }, el('b', {}, s.done ? '✓' : k.icon), el('small', {}, k.name)));
    });
    const legend = el('div', { class: 'wm-legend' }, ...spots.filter((s, i, a) => a.findIndex(x => x.k === s.k) === i).map(s => el('span', {}, el('b', { class: 'k-' + s.k }, KIND[s.k].icon), KIND[s.k].tip)));
    box.append(el('div', { class: 'wm-head' }, el('b', {}, g.loc.place || '四處看看'), el('button', { class: 'btn small', onclick: () => close('leave') }, '離開')), field, tip, legend);
    const close = r => resolve(r);
  });
}

function applyFx(runner, fx) {
  for (const [kind, ...args] of fx) {
    if (kind === '錢' && +args[0] < 0) { runner.effect({ kind, sign: -1, args: [String(-args[0])] }); continue; }
    runner.effect({ kind, sign: 1, args: args.map(String) });
  }
}

function passerby(ctx, runner, vol, { e, i }) {
  const g = ctx.g, ui = ctx.ui;
  return new Promise(resolve => {
    const api = ui.sheet(e.who, body => {
      e.text.forEach(t => body.appendChild(el('p', { class: 'dialog-text' }, ui.fmt(t))));
      body.appendChild(el('div', { class: 'col-btns' }, ...e.opts.map(o => el('button', { class: 'btn', onclick: async () => {
        api.close();
        g.flags[`路人.${vol}.${i}`] = 1;
        applyFx(runner, o.fx || []);
        await ui.alert(e.who, ui.fmt(o.line), '繼續');
        resolve();
      } }, o.label))));
    }, { noClose: true });
  });
}

function riddle(ctx, runner, { id, i, it }, tier) {
  const g = ctx.g, ui = ctx.ui;
  return new Promise(resolve => {
    const api = ui.sheet('謎題', body => {
      body.appendChild(el('p', { class: 'muted small' }, '旁邊有幾個人，在爭論一個問題。你知道答案嗎？'));
      body.appendChild(el('div', { class: 'mg-q' }, it.w));
      body.appendChild(el('div', { class: 'mg-opts' }, ...shuffle(it.opts).map(o => el('button', { class: 'btn mg-opt', onclick: async () => {
        api.close();
        const key = `謎.${id}.${i}`;
        if (o === it.a) {
          ctx.audio.sfx('good');
          if (!g.flags[key]) { g.flags[key] = 1; const n = 20 * tier; g.money += n; await ui.alert('答對了', `旁邊的人都點頭。有人塞給你一點銀子當謝禮。（銀 +${n}）`, '繼續'); }
          else await ui.alert('答對了', '這一題，你以前就答過了。旁邊的人都點頭。', '繼續');
        } else {
          ctx.audio.sfx('fail');
          await ui.alert('不太對', `答案是「${it.a}」。下次就知道了。`, '繼續');
        }
        resolve();
      } }, o))));
    }, { noClose: true });
  });
}
